// Command capgen generates caps_gen.go from pinned web-features and BCD data.
//
// Fetch: sh internal/capgen/fetch.sh /path/to/data
// Generate: go run ./internal/capgen -data /path/to/data
package main

import (
	"bufio"
	"bytes"
	"cmp"
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"maps"
	"math"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

const wfFile = "web-features-3.44.0/package/data.json"
const bcdFile = "browser-compat-data-8.1.7/package/data.json"
const wfHash = "72577e8df9c8abe8a8af86a03bc161ac06be21488d76857f157c7f83f017f706"
const bcdHash = "176cb1ea97c70f2ab8271e65f50643426932d9495e488b7e64925c8febe980f9"

// The order is fixed so map iteration never affects generated bytes.
var browsers = []struct{ mdn, agent, name string }{
	{"chrome", "chrome", "Chrome"}, {"chrome_android", "and_chr", "ChromeAndroid"},
	{"edge", "edge", "Edge"}, {"firefox", "firefox", "Firefox"}, {"firefox_android", "and_ff", "FirefoxAndroid"},
	{"safari", "safari", "Safari"}, {"safari_ios", "ios_saf", "IOSSafari"}, {"ie", "ie", "IE"},
	{"samsunginternet_android", "samsung", "Samsung"}, {"opera", "opera", "Opera"},
	{"opera_android", "op_mob", "OperaAndroid"},
}

type feature struct {
	Kind   string   `json:"kind"`
	Compat []string `json:"compat_features"`
	Status struct {
		Low         string `json:"baseline_low_date"`
		ByCompatKey map[string]struct {
			Low string `json:"baseline_low_date"`
		} `json:"by_compat_key"`
	} `json:"status"`
}

type capability struct {
	Number        int
	Name, Feature string
	Keys          []string
}

type statement struct {
	Added       any               `json:"version_added"`
	Removed     any               `json:"version_removed"`
	Prefix      string            `json:"prefix"`
	Alternative string            `json:"alternative_name"`
	Partial     bool              `json:"partial_implementation"`
	Notes       any               `json:"notes"`
	Flags       []json.RawMessage `json:"flags"`
}

type interval struct{ from, to uint64 }

func main() {
	data := flag.String("data", "", "directory containing the pinned extracted npm releases")
	list := flag.String("list", "internal/capgen/capabilities.tsv", "append-only capability assignments")
	out := flag.String("out", "caps_gen.go", "generated Go file")
	flag.Parse()
	if *data == "" {
		fail(fmt.Errorf("-data is required; fetch with sh internal/capgen/fetch.sh PATH"))
	}
	b, err := generate(*data, *list)
	if err != nil {
		fail(err)
	}
	if err := os.WriteFile(*out, b, 0644); err != nil {
		fail(err)
	}
}

func fail(err error) { fmt.Fprintln(os.Stderr, err); os.Exit(1) }

func source(dir, name, hash string, dst any) error {
	b, err := os.ReadFile(filepath.Join(dir, name))
	if err != nil {
		return err
	}
	if fmt.Sprintf("%x", sha256.Sum256(b)) != hash {
		return fmt.Errorf("%s: SHA-256 mismatch", name)
	}
	return json.Unmarshal(b, dst)
}

func readList(path string) ([]capability, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var caps []capability
	names := map[string]bool{}
	s := bufio.NewScanner(f)
	for s.Scan() {
		line := strings.TrimSpace(s.Text())
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 4 {
			return nil, fmt.Errorf("invalid assignment: %s", line)
		}
		n, err := strconv.Atoi(fields[0])
		if err != nil || n != len(caps) || n >= 256 || !strings.HasPrefix(fields[1], "Cap") || names[fields[1]] {
			return nil, fmt.Errorf("invalid/duplicate wire assignment: %s", line)
		}
		names[fields[1]] = true
		caps = append(caps, capability{n, fields[1], fields[2], fields[3:]})
	}
	return caps, s.Err()
}

func generate(data, list string) ([]byte, error) {
	caps, err := readList(list)
	if err != nil {
		return nil, err
	}
	var wf struct {
		Features map[string]feature `json:"features"`
	}
	if err := source(data, wfFile, wfHash, &wf); err != nil {
		return nil, err
	}
	var bcd map[string]any
	if err := source(data, bcdFile, bcdHash, &bcd); err != nil {
		return nil, err
	}
	var out bytes.Buffer
	fmt.Fprintln(&out, "// Code generated by go run ./internal/capgen; DO NOT EDIT.")
	fmt.Fprintln(&out, "// Sources: web-features 3.44.0; @mdn/browser-compat-data 8.1.7.")
	fmt.Fprintf(&out, "// SHA-256 data.json: %s; %s.\n", wfHash, bcdHash)
	fmt.Fprintln(&out, "\npackage pristinecss\n\n// Browser IDs use caniuse-style names from the mapped browser data.\nconst (")
	for _, browser := range browsers {
		fmt.Fprintf(&out, "%s BrowserID = %q\n", browser.name, browser.agent)
	}
	fmt.Fprintln(&out, ")\n\n// Capability numbers are stable handshake bits. Append assignments in capabilities.tsv.\nconst (")
	for _, c := range caps {
		fmt.Fprintf(&out, "%s Cap = %d\n", c.Name, c.Number)
	}
	fmt.Fprintf(&out, ")\n\nvar capBaseline = [%d]uint16{\n", len(caps))
	for i, c := range caps {
		f, ok := wf.Features[c.Feature]
		if c.Feature != "-" && (!ok || f.Kind != "feature") {
			return nil, fmt.Errorf("%s: missing web-feature %s", c.Name, c.Feature)
		}
		low := baselineLow(f, c.Keys)
		switch {
		case slices.Equal(c.Keys, []string{"*"}):
			caps[i].Keys = f.Compat
		case slices.Equal(c.Keys, []string{"-"}):
			caps[i].Keys = nil
		}
		if low != "" {
			y, _, _ := strings.Cut(strings.TrimPrefix(low, "≤"), "-")
			year, err := strconv.Atoi(y)
			if err != nil {
				return nil, err
			}
			fmt.Fprintf(&out, "%s: %d,\n", c.Name, year)
		}
	}
	fmt.Fprintln(&out, "}\n\nvar capBrowsers = map[BrowserID][]capSupport{")
	for _, browser := range browsers {
		fmt.Fprintf(&out, "%q: {\n", browser.agent)
		for _, c := range caps {
			var full []interval
			for i, key := range c.Keys {
				ss, err := support(bcd, key, browser.mdn, c.Name == "CapDisplayP3")
				if err != nil {
					return nil, fmt.Errorf("%s: %w", c.Name, err)
				}
				if i == 0 {
					full = ss
				} else {
					full = intersect(full, ss)
				}
			}
			for _, span := range full {
				end := span.to
				if end == math.MaxUint64 {
					end = 0
				}
				fmt.Fprintf(&out, "{%s, %#x, %#x},\n", c.Name, span.from, end)
			}
		}
		fmt.Fprintln(&out, "},")
	}
	fmt.Fprintln(&out, "}")
	fmt.Fprintln(&out, "\nvar prefixedProperties = map[string][]prefixSupport{")
	properties := bcd["css"].(map[string]any)["properties"].(map[string]any)
	for _, property := range slices.Sorted(maps.Keys(properties)) {
		for _, prefix := range []string{"-webkit-", "-moz-", "-ms-", "-o-"} {
			var entries bytes.Buffer
			for _, browser := range browsers {
				spans, err := support(bcd, "css.properties."+property+"@"+prefix, browser.mdn, false)
				if err != nil {
					return nil, err
				}
				for _, span := range spans {
					end := span.to
					if end == math.MaxUint64 {
						end = 0
					}
					fmt.Fprintf(&entries, "{%s, %#x, %#x},\n", browser.name, span.from, end)
				}
			}
			if entries.Len() != 0 {
				fmt.Fprintf(&out, "%q: {\n%s},\n", prefix+property, entries.Bytes())
			}
		}
	}
	fmt.Fprintln(&out, "}")
	return format.Source(out.Bytes())
}

// baselineLow returns a row's Baseline low date: the feature's date for "*",
// otherwise the latest date among its keys, or "" if any key has none.
func baselineLow(f feature, keys []string) string {
	if slices.Equal(keys, []string{"*"}) {
		return f.Status.Low
	}
	var low string
	for _, key := range keys {
		date := strings.TrimPrefix(f.Status.ByCompatKey[key].Low, "≤")
		if date == "" {
			return ""
		}
		low = max(low, date)
	}
	return low
}

func version(s string) (uint64, error) {
	parts := strings.Split(strings.TrimPrefix(s, "≤"), ".")
	if len(parts) > 4 {
		return 0, fmt.Errorf("invalid version %q", s)
	}
	var v uint64
	for i, p := range parts {
		n, err := strconv.ParseUint(p, 10, 16)
		if err != nil {
			return 0, fmt.Errorf("invalid version %q: %w", s, err)
		}
		v |= n << (48 - 16*i)
	}
	return v, nil
}

func support(bcd map[string]any, key, browser string, displayP3 bool) ([]interval, error) {
	key, prefix, _ := strings.Cut(key, "@")
	var node any = bcd
	for _, part := range strings.Split(key+".__compat.support", ".") {
		m, ok := node.(map[string]any)
		if !ok {
			return nil, fmt.Errorf("missing BCD key %s", key)
		}
		node = m[part]
	}
	m, ok := node.(map[string]any)
	if !ok {
		return nil, fmt.Errorf("missing BCD support %s", key)
	}
	raw, ok := m[browser]
	if !ok {
		return nil, nil
	}
	b, err := json.Marshal(raw)
	if err != nil {
		return nil, err
	}
	if _, ok := raw.([]any); !ok {
		b = append(append([]byte{'['}, b...), ']')
	}
	var statements []statement
	if err := json.Unmarshal(b, &statements); err != nil {
		return nil, err
	}
	var spans []interval
	for _, s := range statements {
		added, ok := s.Added.(string)
		// BCD's partial Safari color() implementation fully supports this
		// narrower surface, but not CapColorFunction's other profiles.
		partialP3 := displayP3 && key == "css.types.color.color" && s.Notes == "Only supports <code>display-p3</code> and <code>srgb</code> predefined color profiles."
		if !ok || added == "preview" || s.Prefix != prefix || s.Alternative != "" || (s.Partial && !partialP3 && prefix == "") || len(s.Flags) != 0 {
			continue
		}
		start, err := version(added)
		if err != nil {
			return nil, err
		}
		end := uint64(math.MaxUint64)
		if s.Removed != nil && s.Removed != false {
			removed, ok := s.Removed.(string)
			if !ok {
				continue
			} // Removal date unknown: cannot establish a full interval.
			if removed != "preview" {
				end, err = version(removed)
				if err != nil {
					return nil, err
				}
			}
		}
		if start < end {
			spans = append(spans, interval{start, end})
		}
	}
	return union(spans), nil
}

func union(spans []interval) []interval {
	slices.SortFunc(spans, func(a, b interval) int { return cmp.Or(cmp.Compare(a.from, b.from), cmp.Compare(a.to, b.to)) })
	var out []interval
	for _, span := range spans {
		if len(out) > 0 && span.from <= out[len(out)-1].to {
			out[len(out)-1].to = max(out[len(out)-1].to, span.to)
		} else {
			out = append(out, span)
		}
	}
	return out
}

func intersect(a, b []interval) []interval {
	var out []interval
	for _, x := range a {
		for _, y := range b {
			lo, hi := max(x.from, y.from), min(x.to, y.to)
			if lo < hi {
				out = append(out, interval{lo, hi})
			}
		}
	}
	return union(out)
}
